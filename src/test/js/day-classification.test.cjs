for(const [name,expected,prescription,provisional,focus] of cases){
 test('day classification scenario: '+name,()=>{
   const planned=prescription.map(([code,sets])=>({code,sets}));
   for(const item of planned){
     if(item.code==='notARealVariant')continue;
     assert.ok(catalog.variants.some(v=>v.code===item.code),'Unknown catalog fixture '+item.code);
   }
   const actual=classifyDay(planned,catalog);
   assert.equal(actual.structure,expected,JSON.stringify(actual));
   assert.equal(actual.provisional,provisional,JSON.stringify(actual));
   if(focus)assert.equal(actual.focus[0],focus,JSON.stringify(actual));
 });
}
test('type labels depend on the set distribution, not exercise count alone',()=>{
 const a=classifyDay([
  {code:'benchPressBarbellFlatMediumGrip',sets:2},
  {code:'benchPressBarbellInclineMediumGrip',sets:2},
  {code:'chestFlyPecDeckSeated',sets:2},
  {code:'seatedCableRowNeutralGrip',sets:8}
 ],catalog);
 assert.equal(a.groupSets.CHEST,6);
 assert.equal(a.groupSets.BACK,8);
 assert.equal(a.structure,'UPPER');
});
test('different exercise variants in the same anatomical group do not multiply series',()=>{
 const a=classifyDay([{code:'benchPressBarbellFlatMediumGrip',sets:3}],catalog);
 assert.equal(a.groupSets.CHEST,3);
 assert.equal(a.totalSets,3);
});
test('prototype never modifies exercises or the catalog fixture',()=>{
 const input=[{code:'benchPressBarbellFlatMediumGrip',sets:4}];
 const before=JSON.stringify(input);
 classifyDay(input,catalog);
 assert.equal(JSON.stringify(input),before);
});
