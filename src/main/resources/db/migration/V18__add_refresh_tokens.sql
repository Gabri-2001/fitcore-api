CREATE TABLE refresh_tokens (
    id bigint generated by default as identity PRIMARY KEY,
    user_credential_id bigint NOT NULL,
    token_hash varchar(64) NOT NULL UNIQUE,
    expires_at timestamp(6) with time zone NOT NULL,
    revoked_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT fk_refresh_token_credential
        FOREIGN KEY (user_credential_id) REFERENCES user_credentials (id) ON DELETE CASCADE
);

CREATE INDEX idx_refresh_tokens_credential_active
    ON refresh_tokens (user_credential_id, revoked_at, expires_at);
