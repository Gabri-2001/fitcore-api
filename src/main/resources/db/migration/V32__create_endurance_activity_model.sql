-- V32: Independent endurance activities, compatible with manual and future FIT imports.
-- No credentials, third-party content or GPS routes are fetched by this migration.
CREATE TABLE endurance_activities (
 id bigint generated by default as identity primary key,
 user_id bigint not null references users(id),
 activity_type varchar(32) not null,
 source varchar(24) not null default 'MANUAL',
 external_activity_id varchar(180),
 started_at timestamp(6) with time zone not null,
 elapsed_seconds integer not null,
 moving_seconds integer not null,
 distance_meters numeric(12,2) not null,
 elevation_gain_meters numeric(10,2),
 average_heart_rate integer,
 average_cadence integer,
 average_power_watts integer,
 notes varchar(1500),
 created_at timestamp(6) with time zone not null,
 updated_at timestamp(6) with time zone not null,
 CONSTRAINT endurance_activity_type_check CHECK(activity_type IN ('RUN','TRAIL_RUN','TREADMILL','WALK','BIKE')),
 CONSTRAINT endurance_source_check CHECK(source IN ('MANUAL','FIT_FILE','GARMIN','STRAVA')),
 CONSTRAINT endurance_times_check CHECK(moving_seconds > 0 AND elapsed_seconds >= moving_seconds),
 CONSTRAINT endurance_distance_check CHECK(distance_meters >= 0),
 CONSTRAINT endurance_hr_check CHECK(average_heart_rate IS NULL OR average_heart_rate BETWEEN 20 AND 260),
 CONSTRAINT endurance_cadence_check CHECK(average_cadence IS NULL OR average_cadence >= 0),
 CONSTRAINT endurance_elevation_check CHECK(elevation_gain_meters IS NULL OR elevation_gain_meters >= 0)
);
CREATE UNIQUE INDEX endurance_unique_source_id ON endurance_activities(user_id,source,external_activity_id)
 WHERE external_activity_id IS NOT NULL;
CREATE INDEX endurance_user_started_at_idx ON endurance_activities(user_id,started_at DESC);
CREATE TABLE endurance_laps (
 id bigint generated by default as identity primary key,
 activity_id bigint not null references endurance_activities(id) ON DELETE CASCADE,
 lap_number integer not null,
 distance_meters numeric(12,2) not null,
 duration_seconds integer not null,
 average_heart_rate integer,
 created_at timestamp(6) with time zone not null,
 updated_at timestamp(6) with time zone not null,
 CONSTRAINT endurance_lap_number_check CHECK(lap_number > 0),
 CONSTRAINT endurance_lap_duration_check CHECK(duration_seconds > 0),
 CONSTRAINT endurance_lap_distance_check CHECK(distance_meters >= 0),
 CONSTRAINT endurance_laps_unique_number UNIQUE(activity_id,lap_number)
);
-- Prepared for sensor samples/FIT data: null fields represent unavailable sensors.
CREATE TABLE endurance_samples (
 id bigint generated by default as identity primary key,
 activity_id bigint not null references endurance_activities(id) ON DELETE CASCADE,
 recorded_at timestamp(6) with time zone not null,
 latitude numeric(10,7),longitude numeric(10,7),
 distance_meters numeric(12,2),heart_rate integer,cadence integer,power_watts integer,
 altitude_meters numeric(10,2),
 CONSTRAINT sample_lat_check CHECK(latitude IS NULL OR latitude BETWEEN -90 AND 90),
 CONSTRAINT sample_lon_check CHECK(longitude IS NULL OR longitude BETWEEN -180 AND 180)
);
CREATE INDEX endurance_samples_activity_time ON endurance_samples(activity_id, recorded_at);
